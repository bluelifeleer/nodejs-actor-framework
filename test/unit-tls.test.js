const FIXTURES = path.join(import.meta.dirname, '..', 'packages', 'core', 'test', 'fixtures', 'tls');

/** Throwaway certificates generated by scripts/gen-test-certs.sh. */
function tlsConfig(nodeName, overrides = {}) {
  return {
    enabled: true,
    key: path.join(FIXTURES, `${nodeName}.key`),
    cert: path.join(FIXTURES, `${nodeName}.crt`),
    ca: path.join(FIXTURES, 'ca.crt'),
    requestCert: true,
    rejectUnauthorized: true,
    verifyNodeId: true,
    minVersion: 'TLSv1.2',
    ...overrides,
  };
}

async function withGateways(specs, fn) {
  const gateways = specs.map(
    (spec, index) =>
      new Gateway({
        host: '127.0.0.1',
        port: 0,
        nodeId: spec.nodeId || `G${index}`,
        tls: spec.tls,
        onDeliver: spec.onDeliver || (async () => null),
      }),
  );
  try {
    for (const gw of gateways) await gw.listen();
    return await fn(gateways);
  } finally {
    for (const gw of gateways) {
      try {
        await gw.close();
      } catch {
        /* already closed */
      }
    }
  }
}

test('tls: the fixtures are present and the CA signs both node certs', () => {
  for (const file of ['ca.crt', 'node-1.crt', 'node-1.key', 'node-2.crt', 'node-2.key', 'imposter.crt']) {
    assert.ok(fs.existsSync(path.join(FIXTURES, file)), `missing fixture ${file}`);
  }
});

test('tls: mutually authenticated peers deliver and ping', async () => {
  await withGateways(
    [
      {
        nodeId: 'node-1',
        tls: tlsConfig('node-1'),
        onDeliver: async (target, payload) => ({ target, payload, answeredBy: 'node-1' }),
      },
      { nodeId: 'node-2', tls: tlsConfig('node-2') },
    ],
    async ([a, b]) => {
      assert.strictEqual(await b.ping('127.0.0.1', a.port), true);
      const result = await b.deliver('127.0.0.1', a.port, 'actor-1', { type: 'x', n: 5 });
      assert.deepStrictEqual(result, { target: 'actor-1', payload: { type: 'x', n: 5 }, answeredBy: 'node-1' });
      assert.strictEqual(await a.ping('127.0.0.1', b.port), true, 'mutual TLS works in both directions');
    },
  );
});

test('tls: a certificate from an untrusted CA cannot connect', async () => {
  const rogueTls = {
    enabled: true,
    key: path.join(FIXTURES, 'imposter.key'),
    cert: path.join(FIXTURES, 'imposter.crt'),
    ca: path.join(FIXTURES, 'rogue-ca.crt'),
    requestCert: true,
    rejectUnauthorized: true,
    verifyNodeId: true,
  };
  await withGateways(
    [{ nodeId: 'node-1', tls: tlsConfig('node-1') }, { nodeId: 'imposter', tls: rogueTls }],
    async ([a, imposter]) => {
      await assert.rejects(
        () => imposter.deliver('127.0.0.1', a.port, 'actor-1', { type: 'x' }, 3000),
        /timed out|closed|socket hang up|ECONNRESET|self.signed|unable to verify|alert/i,
      );
    },
  );
});

test('tls: a plaintext client cannot talk to a TLS gateway', async () => {
  await withGateways([{ nodeId: 'node-1', tls: tlsConfig('node-1') }], async ([a]) => {
    const socket = net.createConnection({ host: '127.0.0.1', port: a.port });
    const outcome = await new Promise((resolve) => {
      const timer = setTimeout(() => resolve('timeout'), 2500);
      socket.on('error', () => {
        clearTimeout(timer);
        resolve('error');
      });
      socket.on('close', () => {
        clearTimeout(timer);
        resolve('close');
      });
      socket.on('data', () => {
        clearTimeout(timer);
        resolve('data');
      });
      socket.write('GET / HTTP/1.1\r\n\r\n');
    });
    socket.destroy();
    assert.notStrictEqual(outcome, 'data', 'a plaintext peer must not get a usable session');
  });
});

test('tls: a client certificate from another node cannot borrow a nodeId', async () => {
  const serverErrors = [];
  const server = new Gateway({ host: '127.0.0.1', port: 0, nodeId: 'node-1', tls: tlsConfig('node-1'), onDeliver: async () => 'ok' });
  server.on('auth_error', (reason) => serverErrors.push(reason));
  // Holds node-2's certificate but claims to be node-1.
  const liar = new Gateway({ host: '127.0.0.1', port: 0, nodeId: 'node-1', tls: tlsConfig('node-2'), onDeliver: async () => null });
  try {
    await server.listen();
    await liar.listen();
    await assert.rejects(
      () => liar.deliver('127.0.0.1', server.port, 'actor-1', { type: 'x' }, 3000),
      /timed out|closed|socket hang up|ECONNRESET/i,
    );
    await waitFor(() => serverErrors.length > 0, { message: 'an auth_error to be reported', timeout: 3000 });
    assert.match(serverErrors[0], /certificate CN is "node-2"/);
  } finally {
    await server.close();
    await liar.close();
  }
});

test('tls: nodeId binding can be disabled for rolling upgrades', async () => {
  await withGateways(
    [
      { nodeId: 'node-1', tls: tlsConfig('node-1', { verifyNodeId: false }), onDeliver: async () => 'answered' },
      { nodeId: 'node-1', tls: tlsConfig('node-2') }, // mismatched identity, tolerated by the server
    ],
    async ([a, b]) => {
      assert.strictEqual(await b.deliver('127.0.0.1', a.port, 'actor-1', {}), 'answered');
    },
  );
});

test('tls: a client without a certificate is rejected when requestCert is on', async () => {
  await withGateways([{ nodeId: 'node-1', tls: tlsConfig('node-1') }], async ([a]) => {
    const { encodeFrame, CODEC } = _gateway;
    const socket = tls.connect({
      host: '127.0.0.1',
      port: a.port,
      ca: fs.readFileSync(path.join(FIXTURES, 'ca.crt')),
      servername: 'localhost',
      rejectUnauthorized: false, // accept the server cert; we are testing the server's check
    });

    // With TLS 1.3 the client's handshake can finish before the server has
    // processed the (missing) client certificate, so the meaningful assertion
    // is that no usable session exists: the peer never answers.
    const outcome = await new Promise((resolve) => {
      let sawData = false;
      const timer = setTimeout(() => resolve(sawData ? 'data' : 'timeout'), 2500);
      const done = (result) => {
        if (sawData) result = 'data';
        clearTimeout(timer);
        resolve(result);
      };
      socket.on('data', () => {
        sawData = true; // any response at all would be a protocol violation
      });
      socket.on('error', () => done('error'));
      socket.on('close', () => done('close'));
      socket.on('secureConnect', () => {
        socket.write(encodeFrame({ kind: 'hello', nodeId: 'anonymous' }, CODEC.PROTOBUF));
      });
    });
    socket.destroy();
    assert.ok(['error', 'close'].includes(outcome), `expected the peer to be dropped, got "${outcome}"`);
  });
});

test('tls: gossip converges over mutual TLS', async () => {
  const g1 = new Gossip('node-1', 0, {
    host: '127.0.0.1',
    advertiseHost: '127.0.0.1',
    intervalMs: 100,
    tls: tlsConfig('node-1'),
  });
  await g1.start();
  const g2 = new Gossip('node-2', 0, {
    host: '127.0.0.1',
    advertiseHost: '127.0.0.1',
    intervalMs: 100,
    tls: tlsConfig('node-2'),
    seeds: [{ host: '127.0.0.1', port: g1.boundPort }],
  });
  await g2.start();

  try {
    g1.setLocal('actor-tls', { type: 'actor', host: '127.0.0.1', gatewayPort: 1234 });
    await waitFor(() => g2.localRegistry.has('actor-tls'), { message: 'gossip over TLS', timeout: 10000 });
    assert.strictEqual(g2.localRegistry.get('actor-tls').value.gatewayPort, 1234);
  } finally {
    await g1.stop();
    await g2.stop();
  }
});

test('tls: gossip rejects a peer that claims another nodeId', async () => {
  const honest = new Gossip('node-1', 0, {
    host: '127.0.0.1',
    advertiseHost: '127.0.0.1',
    intervalMs: 100,
    tls: tlsConfig('node-1'),
  });
  const authErrors = [];
  honest.on('auth_error', (reason) => authErrors.push(reason));
  await honest.start();

  // Presents node-1's certificate while claiming to be node-9.
  const liar = new Gossip('node-9', 0, {
    host: '127.0.0.1',
    advertiseHost: '127.0.0.1',
    intervalMs: 100,
    tls: tlsConfig('node-1'),
    seeds: [{ host: '127.0.0.1', port: honest.boundPort }],
  });
  await liar.start();

  try {
    await waitFor(() => authErrors.length > 0, { message: 'gossip to reject the mismatched nodeId', timeout: 8000 });
    assert.match(authErrors[0], /certificate CN is "node-1"/);
  } finally {
    await honest.stop();
    await liar.stop();
  }
});

test('tls: missing key material is a loud failure, not a silent plaintext fallback', () => {
  const tlsUtil = _tls_util;
  assert.throws(() => tlsUtil.serverOptions({ enabled: true, key: '', cert: '', ca: '' }), /ACTOR_TLS_KEY/);
  assert.throws(
    () => tlsUtil.serverOptions({ enabled: true, key: '/nope.key', cert: '/nope.crt', ca: '/nope.ca' }),
    /cannot read ACTOR_TLS_KEY/,
  );
});

test('tls: bootstrap disables the gateway instead of running it in plaintext', async () => {
  const { bootstrap } = _actor_main;
  const ctx = await bootstrap({
    nodeId: 'broken-tls',
    telnet: { enabled: false },
    gossip: { enabled: false },
    gateway: { enabled: true, port: 0, host: '127.0.0.1' },
    tls: { enabled: true, key: '/does/not/exist.key', cert: '/does/not/exist.crt', ca: '/does/not/exist.ca' },
    bootActors: [],
  });
  try {
    assert.strictEqual(ctx.ports.gateway, null, 'the gateway must not be exposed');
    assert.strictEqual(ctx.system.server, null, 'no plaintext listener is left behind');
    assert.ok(ctx.warnings.some((w) => /gateway could not listen/.test(w)));
  } finally {
    await ctx.close();
  }
});
