import { createPgDriver } from '../drivers/pg.ts';
import {
  hostConnectionFromFields,
  hostConnectionFromUrl,
  hostDescribe,
  normalizeTypeText,
  numericLiteral,
  sqlString,
  typeRendererFor,
  type ColumnTypeOptions,
  type DialectSpec,
  type LogicalType,
  type RenderableField,
  type RenderableModel,
  type TypeRenderers,
} from './types.ts';

/**
 * PostgreSQL 的类型表：**一个逻辑类型一行**（方案 A）。
 * 加类型＝加一行；TS 的 `Record<LogicalType, …>` 会强迫这里补齐每个类型。
 */
const TYPES: TypeRenderers = {
  uuid: () => 'uuid',
  string: (o) => (o.length === undefined ? 'text' : `varchar(${o.length})`),
  char: (o) => `char(${o.length ?? 1})`,
  text: () => 'text',
  tinyText: () => 'text',
  mediumText: () => 'text',
  bigText: () => 'text',
  tinyint: () => 'smallint', // PG 没有 1 字节整数
  smallint: () => 'smallint',
  integer: () => 'integer',
  bigint: () => 'bigint',
  decimal: (o) => `numeric(${o.precision ?? 10}, ${o.scale ?? 2})`,
  float: () => 'real',
  real: () => 'double precision',
  boolean: () => 'boolean',
  date: () => 'date',
  time: () => 'time',
  timestamp: () => 'timestamptz',
  dateTime: () => 'timestamp', // 不带时区
  json: () => 'jsonb',
  blob: () => 'bytea',
  binary: () => 'bytea',
};

/**
 * pg 的 information_schema 用的是"听起来对"的名字：`character varying` / `timestamp with time zone`。
 * 先做方言别名映射，再走通用规则（小写 + 需要时补长度）。
 */
function normalizeDbType(rawType: string, options: { length?: number | null }): string {
  let text = String(rawType).toLowerCase().trim();
  if (text === 'character varying') text = 'varchar';
  if (text === 'timestamp with time zone') text = 'timestamptz';
  if (text === 'timestamp without time zone') text = 'timestamp';
  return normalizeTypeText(text, options.length);
}

const DEFAULT_PORT = 5432;

function quote(name: string): string {
  return `"${String(name).split('"').join('""')}"`;
}

export const pgsql: DialectSpec = {
  name: 'pgsql',
  urlSchemes: ['pgsql', 'postgres', 'postgresql'],
  driverPackage: 'pg',
  driver: () => createPgDriver(),
  defaultPort: DEFAULT_PORT,
  placeholder: (index) => `$${index}`,
  quote,
  quoteTable: (schema, table) => (schema === undefined ? quote(table) : `${quote(schema)}.${quote(table)}`),
  supportsReturning: true,
  columnType: (logical: LogicalType, options: ColumnTypeOptions) => typeRendererFor(TYPES, logical, 'pgsql')(options),

  createTable: (model, columns) => `CREATE TABLE IF NOT EXISTS ${quote(model.table)} (${columns})`,
  alterAddColumn: (table, column) => `ALTER TABLE ${table} ADD COLUMN ${column}`,

  // IDENTITY 写在类型之后、NOT NULL 之前
  autoIncrementPieces: (field: RenderableField) =>
    field.autoIncrement ? { beforeNotNull: 'GENERATED BY DEFAULT AS IDENTITY' } : null,

  defaultLiteral: (field: RenderableField) => {
    if (!field.hasDefault) return null;
    const value = field.defaultValue;
    if (value === null) return 'NULL';
    if (typeof value === 'number' || typeof value === 'bigint') return numericLiteral(field.name, value);
    // pg 的 boolean 列不接受 1/0
    if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
    const text = typeof value === 'string' ? value : JSON.stringify(value);
    // json/jsonb 的默认值必须带类型转换，否则报 "column is of type jsonb but expression is of type text"
    if (field.type === 'json') return `${sqlString(String(text))}::jsonb`;
    return sqlString(String(text));
  },

  // pg 没有内联列注释（走独立的 COMMENT ON）
  inlineComment: () => null,
  tableSuffix: () => '',
  commentStatements: (model: RenderableModel) => {
    const statements: string[] = [];
    if (model.comment !== undefined) {
      statements.push(`COMMENT ON TABLE ${quote(model.table)} IS ${sqlString(model.comment)}`);
    }
    for (const field of model.fields) {
      if (field.comment === undefined) continue;
      statements.push(`COMMENT ON COLUMN ${quote(model.table)}.${quote(field.column)} IS ${sqlString(field.comment)}`);
    }
    return statements;
  },
  indexIfNotExists: true,
  // 只有 MySQL 需要"索引已存在"的补偿
  isDuplicateIndexError: () => false,

  introspection: {
    tableExists: (table) => ({
      sql: 'SELECT 1 AS found FROM information_schema.tables WHERE table_name = $1 AND table_schema = current_schema()',
      params: [table],
    }),
    columns: (table) => ({
      sql:
        'SELECT column_name, is_nullable, data_type, character_maximum_length, column_default ' +
        'FROM information_schema.columns WHERE table_name = $1 AND table_schema = current_schema() ORDER BY ordinal_position',
      params: [table],
    }),
    toColumn: (row) => {
      const rawType = String(row.data_type ?? row.column_type ?? '');
      const length =
        row.character_maximum_length === undefined || row.character_maximum_length === null
          ? null
          : Number(row.character_maximum_length);
      return {
        name: String(row.column_name),
        type: normalizeDbType(rawType, { length }),
        rawType,
        notNull: String(row.is_nullable).toUpperCase() === 'NO',
        hasDefault: row.column_default !== null && row.column_default !== undefined,
      };
    },
  },

  normalizeDbType,

  serializeBoolean: (value) => Boolean(value), // pg 的 boolean 列不接受 1/0
  serializeTimestamp: (date) => date,
  comments: 'statements',

  connectionKind: 'host',
  connectionFromFields: (input) => hostConnectionFromFields(input, 'pgsql', DEFAULT_PORT),
  connectionFromUrl: (url) => hostConnectionFromUrl(url, 'pgsql', DEFAULT_PORT),
  describe: (connection) => hostDescribe(connection, DEFAULT_PORT),
};
