import { test } from 'node:test';
import assert from 'node:assert';

import { columnTypeFor, defineModel, DIALECTS, dialectSpec } from '../src/index.ts';
import { DIALECT_SPECS } from '../src/dialects/index.ts';

/**
 * 方言描述符（`DialectSpec`）的契约测试 —— 设计见 docs/design/m6-dialect-spec.md。
 *
 * 这是"加方言只需一个文件"的**可执行契约**：
 *   - 注册表必须覆盖 `DIALECTS` 里的每一个方言；
 *   - 每个方言必须能给**每一个**逻辑类型**出**一个非空列类型（漏掉一个就是 bug，而不是"运行时才知道"）；
 *   - 公开的旧函数（`columnTypeFor` 等）必须与描述符给出**完全相同**的结果（重构不改行为）。
 */
const LOGICAL_TYPES = [
  'uuid', 'string', 'char', 'text', 'tinyText', 'mediumText', 'bigText',
  'tinyint', 'smallint', 'integer', 'bigint', 'decimal', 'float', 'real',
  'boolean', 'date', 'time', 'timestamp', 'dateTime', 'json', 'blob', 'binary',
] as const;

test('dialect-spec: 注册表覆盖所有方言，且每个方言对每个逻辑类型都能给出列类型', () => {
  assert.deepStrictEqual(
    Object.keys(DIALECT_SPECS).sort(),
    [...DIALECTS].sort(),
    '描述符注册表与公开的 DIALECTS 不一致',
  );
  for (const dialect of DIALECTS) {
    const spec = dialectSpec(dialect);
    assert.strictEqual(spec.name, dialect);
    assert.ok(spec.driverPackage.length > 0, `${dialect} 缺少 driverPackage`);
    for (const logical of LOGICAL_TYPES) {
      const type = spec.columnType(logical, { length: 8, precision: 12, scale: 3 });
      assert.strictEqual(typeof type, 'string', `${dialect}.${logical} 没给出列类型`);
      assert.ok(type.trim().length > 0, `${dialect}.${logical} 的列类型是空的`);
    }
  }
});

test('dialect-spec: 未知方言要明确报错（不能静默当成某一个）', () => {
  assert.throws(() => dialectSpec('oracle' as never), /unknown dialect/i);
});

test('dialect-spec: 公开函数与描述符结果一致（重构不改行为）', () => {
  for (const dialect of DIALECTS) {
    const spec = dialectSpec(dialect);
    for (const logical of LOGICAL_TYPES) {
      assert.strictEqual(
        columnTypeFor(dialect, logical as never, { length: 4 }),
        spec.columnType(logical as never, { length: 4 }),
        `${dialect}.${logical}: 公开函数与描述符结果不一致`,
      );
    }
    assert.strictEqual(spec.placeholder(3), dialect === 'pgsql' ? '$3' : '?');
    assert.strictEqual(spec.quote('x'), dialect === 'mysql' ? '`x`' : '"x"');
  }
});

test('dialect-spec: 列定义的方言片段 —— 自增身份 / 默认值 / 内联注释 / 表后缀 / 注释语句', () => {
  const model = defineModel({
    name: 'notes',
    comment: '表注释',
    fields: {
      id: { type: 'integer', primaryKey: true, autoIncrement: true },
      flag: { type: 'boolean', default: true },
      tags: { type: 'json', default: [] },
      body: { type: 'text', default: 'x' },
      title: { type: 'string', comment: "标题（it's）" },
    },
  });
  const id = model.fieldFor('id');
  const flag = model.fieldFor('flag');
  const tags = model.fieldFor('tags');
  const body = model.fieldFor('body');
  const title = model.fieldFor('title');

  // --- 自增身份：三种写法，别的方言不该有别人的片段 ---
  assert.deepStrictEqual(dialectSpec('pgsql').autoIncrementPieces(id), { beforeNotNull: 'GENERATED BY DEFAULT AS IDENTITY' });
  assert.deepStrictEqual(dialectSpec('mysql').autoIncrementPieces(id), { afterNotNull: 'AUTO_INCREMENT' });
  assert.deepStrictEqual(dialectSpec('sqlite').autoIncrementPieces(id), { override: '"id" integer PRIMARY KEY AUTOINCREMENT' });
  assert.strictEqual(dialectSpec('pgsql').autoIncrementPieces(title), null, '非自增字段必须返回 null');

  // --- 默认值字面量：布尔、JSON 类型转换、MySQL 的 TEXT 不给默认值 ---
  assert.strictEqual(dialectSpec('pgsql').defaultLiteral(flag), 'TRUE');
  assert.strictEqual(dialectSpec('mysql').defaultLiteral(flag), '1');
  assert.strictEqual(dialectSpec('sqlite').defaultLiteral(flag), '1');
  assert.strictEqual(dialectSpec('pgsql').defaultLiteral(tags), `'[]'::jsonb`);
  assert.strictEqual(dialectSpec('sqlite').defaultLiteral(tags), `'[]'`);
  assert.strictEqual(dialectSpec('mysql').defaultLiteral(body), null, 'MySQL 的 TEXT 列不给默认值');
  assert.strictEqual(dialectSpec('pgsql').defaultLiteral(title), null, '没有默认值的字段不该编出一个');

  // --- 内联注释：只有 MySQL 有（且要转义） ---
  assert.strictEqual(dialectSpec('mysql').inlineComment(title), `'标题（it''s）'`);
  assert.strictEqual(dialectSpec('pgsql').inlineComment(title), null);
  assert.strictEqual(dialectSpec('sqlite').inlineComment(title), null);

  // --- 表级后缀 / 独立注释语句 ---
  assert.strictEqual(dialectSpec('mysql').tableSuffix(model, { withComments: true }), ` COMMENT='表注释'`);
  assert.strictEqual(dialectSpec('mysql').tableSuffix(model, { withComments: false }), '');
  assert.strictEqual(dialectSpec('pgsql').tableSuffix(model, { withComments: true }), '');
  assert.deepStrictEqual(dialectSpec('pgsql').commentStatements(model), [
    `COMMENT ON TABLE "notes" IS '表注释'`,
    `COMMENT ON COLUMN "notes"."title" IS '标题（it''s）'`,
  ]);
  assert.deepStrictEqual(dialectSpec('sqlite').commentStatements(model), []);
  assert.deepStrictEqual(dialectSpec('mysql').commentStatements(model), []);

  // --- 索引能力与错误容忍 ---
  assert.strictEqual(dialectSpec('mysql').indexIfNotExists, false, 'MySQL 没有 CREATE INDEX IF NOT EXISTS');
  assert.strictEqual(dialectSpec('pgsql').indexIfNotExists, true);
  assert.strictEqual(dialectSpec('sqlite').indexIfNotExists, true);
  assert.strictEqual(dialectSpec('mysql').isDuplicateIndexError(new Error('ER_DUP_KEYNAME: Duplicate key name')), true);
  assert.strictEqual(dialectSpec('mysql').isDuplicateIndexError(new Error('connection reset')), false);
  assert.strictEqual(dialectSpec('pgsql').isDuplicateIndexError(new Error('ER_DUP_KEYNAME')), false, '只有 MySQL 需要这种补偿');
});

test('dialect-spec: 内省 SQL 与行映射（sqlite 的 PRAGMA 形状特殊，不能硬塞进 {sql,params}）', () => {
  // 表存在性：pg 用 $1，mysql 限定当前库，sqlite 查 sqlite_master
  const pgExists = dialectSpec('pgsql').introspection.tableExists('notes');
  assert.deepStrictEqual(pgExists.params, ['notes']);
  assert.match(pgExists.sql, /information_schema\.tables/);
  assert.match(pgExists.sql, /\$1/);
  const mysqlExists = dialectSpec('mysql').introspection.tableExists('notes');
  assert.match(mysqlExists.sql, /DATABASE\(\)/);
  const sqliteExists = dialectSpec('sqlite').introspection.tableExists('notes');
  assert.deepStrictEqual(sqliteExists.params, ['table', 'notes']);
  assert.match(sqliteExists.sql, /sqlite_master/);

  // 列内省：sqlite 是 PRAGMA（不支持占位符）→ 用 { pragma } 形状
  const sqliteColumns = dialectSpec('sqlite').introspection.columns('notes');
  assert.ok('pragma' in sqliteColumns, 'sqlite 的列内省应当是 PRAGMA 形状');
  assert.strictEqual(sqliteColumns.pragma, 'PRAGMA table_info("notes")');
  const pgColumns = dialectSpec('pgsql').introspection.columns('notes');
  assert.ok('sql' in pgColumns && pgColumns.sql.includes('ordinal_position'));

  // 行映射：两种行形状各自归一
  assert.deepStrictEqual(
    dialectSpec('sqlite').introspection.toColumn({ name: 'id', type: 'integer', notnull: 1, pk: 1, dflt_value: null }),
    { name: 'id', type: 'integer', rawType: 'integer', notNull: true, hasDefault: false },
  );
  assert.deepStrictEqual(
    dialectSpec('pgsql').introspection.toColumn({
      column_name: 'title', data_type: 'character varying', character_maximum_length: 200, is_nullable: 'YES', column_default: null,
    }),
    { name: 'title', type: 'varchar(200)', rawType: 'character varying', notNull: false, hasDefault: false },
  );
  assert.deepStrictEqual(
    dialectSpec('mysql').introspection.toColumn({
      column_name: 'flag', column_type: 'tinyint(1)', is_nullable: 'NO', column_default: '0',
    }),
    { name: 'flag', type: 'tinyint(1)', rawType: 'tinyint(1)', notNull: true, hasDefault: true },
  );

  // 类型规范化：pg 的别名要归一，长度只在需要时补
  assert.strictEqual(dialectSpec('pgsql').normalizeDbType('character varying', { length: 4 }), 'varchar(4)');
  assert.strictEqual(dialectSpec('pgsql').normalizeDbType('timestamp with time zone', {}), 'timestamptz');
  assert.strictEqual(dialectSpec('pgsql').normalizeDbType('timestamp without time zone', {}), 'timestamp');
  assert.strictEqual(dialectSpec('sqlite').normalizeDbType('INTEGER', {}), 'integer', '要大小写归一');
  assert.strictEqual(dialectSpec('mysql').normalizeDbType('tinyint(1)', {}), 'tinyint(1)');
});

test('dialect-spec: 值表示只搬**真正有差异**的部分（写库的布尔 1/0、时间戳的 ISO 文本）', () => {
  // 解析布尔是通用的（Number(value) === 1），不进描述符 —— 接口只描述真实存在的差异
  assert.strictEqual(dialectSpec('pgsql').serializeBoolean(true), true, 'pg 的 boolean 列不接受 1/0');
  assert.strictEqual(dialectSpec('mysql').serializeBoolean(true), 1);
  assert.strictEqual(dialectSpec('sqlite').serializeBoolean(false), 0);

  const when = new Date('2026-10-07T13:45:06.000Z');
  assert.strictEqual(dialectSpec('sqlite').serializeTimestamp(when), when.toISOString(), 'sqlite 的 timestamp 列是 TEXT');
  assert.strictEqual(dialectSpec('pgsql').serializeTimestamp(when), when);
  assert.strictEqual(dialectSpec('mysql').serializeTimestamp(when), when);
});

test('dialect-spec: 注释能力用能力位表达，而不是在 schema 层写方言名', () => {
  assert.strictEqual(dialectSpec('pgsql').comments, 'statements');
  assert.strictEqual(dialectSpec('mysql').comments, 'inline');
  assert.strictEqual(dialectSpec('sqlite').comments, 'none');
});
